import type { Pix } from "./pix";
import type { Col } from "./palette";

/** Police 3×5 pour les enseignes (uniquement les lettres utilisées par le monde). */
const G: Record<string, string[]> = {
  A: [".#.", "#.#", "###", "#.#", "#.#"],
  B: ["##.", "#.#", "##.", "#.#", "##."],
  C: [".##", "#..", "#..", "#..", ".##"],
  E: ["###", "#..", "##.", "#..", "###"],
  H: ["#.#", "#.#", "###", "#.#", "#.#"],
  I: [".#.", ".#.", ".#.", ".#.", ".#."],
  L: ["#..", "#..", "#..", "#..", "###"],
  N: ["###", "#.#", "#.#", "#.#", "#.#"],
  O: [".#.", "#.#", "#.#", "#.#", ".#."],
  P: ["##.", "#.#", "##.", "#..", "#.."],
  R: ["##.", "#.#", "##.", "#.#", "#.#"],
  S: [".##", "#..", ".#.", "..#", "##."],
  T: ["###", ".#.", ".#.", ".#.", ".#."],
  U: ["#.#", "#.#", "#.#", "#.#", "###"],
  V: ["#.#", "#.#", "#.#", "#.#", ".#."],
  "0": ["###", "#.#", "#.#", "#.#", "###"],
  "1": [".#.", "##.", ".#.", ".#.", "###"],
  "/": ["..#", "..#", ".#.", "#..", "#.."],
  "{": [".##", ".#.", "##.", ".#.", ".##"],
  "}": ["##.", ".#.", ".##", ".#.", "##."],
  " ": ["...", "...", "...", "...", "..."],
};

export const textWidth = (s: string): number => Math.max(0, s.length * 4 - 1);

export function drawText(p: Pix, x: number, y: number, s: string, c: Col): number {
  let cx = x;
  for (const ch of s) {
    const g = G[ch] ?? G[" "];
    g.forEach((row, j) => [...row].forEach((v, i) => v === "#" && p.set(cx + i, y + j, c)));
    cx += 4;
  }
  return textWidth(s);
}
